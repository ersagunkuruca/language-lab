// C for the scalar profile (scalar.ts): the lowering wasm.ts, wgsl.ts and
// js-scalar.ts print, printed as C, the first stage of native programs
// (projectional/NATIVE.md). Number is `double`, Bool is an `int32_t` 0 or
// 1, a record is a struct passed by value, a let is a local, and `if` is
// an `if` statement. Lower with `{ records: true }` to have records.
//
// The numbers are the evaluator's, bit for bit, on any C compiler that
// keeps IEEE 754's rules: + − × ÷, sqrt and floor are exact in C as in
// JavaScript, `mod` is fmod twice (as runtime.js's `$mod`), and sin, cos,
// tan, exp, log, pow and atan2 are V8's fdlibm translated to C (c-math.ts),
// which is what Node's Math runs. What a compiler may do to that, it must
// be told not to: contract a·b + c into one fused step (GCC does on
// aarch64 unless -ffp-contract=off), or keep x87's extra bits on 32-bit
// x86 (-msse2 -mfpmath=sse). CFLAGS has the flags.
//
// A call to itself as the last step is a loop, as in WGSL; other recursion
// recurses. A budget (with fuel) is one variable, `lab_fuel`, spent as in
// the other targets. Data, closures, text and the world come in the later
// stages; until then they're refused here with the stage that brings them.

import { FDLIBM_C } from "./c-math.ts";
import { isRecord, type LType, type Lowered, type Op, type RType, type SExpr, type SFunc } from "./scalar.ts";

// What a C compiler needs to keep the evaluator's numbers.
export const CFLAGS = ["-std=c99", "-O2", "-ffp-contract=off"];

const INFIX: Partial<Record<Op, string>> = {
  add: "+", sub: "-", mul: "*", div: "/", less: "<", equal: "==", beq: "==", and: "&&", or: "||",
};
const LIBM: Partial<Record<Op, string>> = { sqrt: "sqrt", abs: "fabs", floor: "floor" };
const FDLIBM: Partial<Record<Op, string>> = {
  sin: "lab_fdlibm_sin", cos: "lab_fdlibm_cos", tan: "lab_fdlibm_tan", exp: "lab_fdlibm_exp", log: "lab_fdlibm_log", pow: "lab_fdlibm_pow", atan2: "lab_fdlibm_atan2",
};

export interface CProgram { c: string; names: Map<number, string> }

// `harness`: a main that reads calls from standard input, one a line (the
// function's index, then each input's bits in hex), and prints each answer
// the same way, records field by field: how the tests compare with the
// evaluator.
export function emitC(lowered: Lowered, opts: { harness?: boolean } = {}): CProgram {
  const { funcs, records } = lowered;
  const used = new Set<string>();
  const ident = (hint: string) => {
    const base = hint.normalize("NFKD").replace(/[^A-Za-z0-9_]+/g, "_").replace(/^_+|_+$/g, "") || "f";
    let n = base;
    for (let i = 2; used.has(n); i++) n = `${base}_${i}`;
    used.add(n);
    return n;
  };
  const structs = new Map(records.map((r) => [r.key, ident(r.name)]));
  const names = new Map(funcs.map((f, i) => [i, `lab_${ident(f.name)}`]));
  const ty = (t: LType): string => {
    if (t === "f64") return "double";
    if (t === "i32") return "int32_t";
    if (isRecord(t)) return structs.get(t.key)!;
    throw new Error(`a ${typeof t === "string" ? t : "cases" in t ? "data type" : "function"} in C comes with NATIVE.md's later stages`);
  };
  const header = (f: SFunc, i: number) => `${ty(f.result)} ${names.get(i)}(${f.params.map((t, j) => `${ty(t)} p${j}`).join(", ") || "void"})`;
  const math = funcs.some((f) => usesAny(f.body, Object.keys(FDLIBM) as Op[]));
  const text = funcs.map((f, i) => func(f, i));
  const c = [
    "// Generated by compiler/src/c.ts from a typed program. Do not edit.",
    "// Build with -ffp-contract=off (and -msse2 -mfpmath=sse on 32-bit x86):",
    "// the numbers are then the evaluator's, bit for bit.",
    "#pragma STDC FP_CONTRACT OFF",
    "#include <stdint.h>",
    "#include <math.h>",
    ...(math ? [FDLIBM_C] : []),
    "",
    ...records.map((r) => `typedef struct { ${r.fields.map((x, j) => `${ty(x.t)} f${j};`).join(" ")} } ${structs.get(r.key)}; // ${r.name}: ${r.fields.map((x) => x.name).join(", ")}`),
    ...(text.some((t) => t.includes("lab_fuel")) ? ["static double lab_fuel = 0;"] : []),
    ...(text.some((t) => t.includes("lab_mod(")) ? ["static double lab_mod(double a, double b) { return fmod(fmod(a, b) + b, b); }"] : []),
    "",
    ...funcs.map((f, i) => `${header(f, i)};`),
    "",
    text.join("\n\n"),
    ...(opts.harness ? ["", harness()] : []),
    "",
  ].join("\n");
  return { c, names };

  function func(f: SFunc, i: number): string {
    const loops = calls(f.body).some((x) => x.fn === i && x.tail);
    const local = (j: number) => (j < f.params.length ? `p${j}` : `l${j}`);
    let temps = 0;
    const decls: string[] = [];
    const temp = (t: LType) => { const n = `t${temps++}`; decls.push(`  ${ty(t)} ${n};`); return n; };
    // Every local is declared once at the top: a let in one branch of an
    // if is still one variable.
    f.locals.forEach((t, j) => { if (j >= f.params.length) decls.push(`  ${ty(t)} ${local(j)};`); });

    // An expression, with the statements it needs first.
    function ex(e: SExpr, pre: string[], d: string): string {
      switch (e.k) {
        case "num": return num(e.v);
        case "bool": return e.v ? "1" : "0";
        case "local": return local(e.i);
        case "let":
          pre.push(`${d}${local(e.i)} = ${ex(e.value, pre, d)};`);
          return ex(e.body, pre, d);
        case "if": {
          const c = ex(e.cond, pre, d), t = temp(e.t);
          pre.push(`${d}if (${c}) {`, ...block(e.then, { set: t }, d + "  "), `${d}} else {`, ...block(e.else, { set: t }, d + "  "), `${d}}`);
          return t;
        }
        case "make": return `((${ty(e.t)}){ ${e.args.map((a) => ex(a, pre, d)).join(", ")} })`;
        case "get": return `${ex(e.rec, pre, d)}.f${e.i}`;
        case "call": return `${names.get(e.fn)}(${e.args.map((a) => ex(a, pre, d)).join(", ")})`;
        case "budget": {
          const s = temp("f64"), t = temp(e.t);
          pre.push(`${d}${s} = lab_fuel;`, `${d}lab_fuel = ${num(e.n)};`, ...block(e.body, { set: t }, d));
          pre.push(`${d}if (lab_fuel < 0) {`, ...block(e.otherwise, { set: t }, d + "  "), `${d}}`, `${d}lab_fuel = ${s};`);
          return t;
        }
        case "op": {
          const xs = e.args.map((a) => ex(a, pre, d));
          if (INFIX[e.op]) return `(${xs[0]} ${INFIX[e.op]} ${xs[1]})`;
          if (e.op === "neg") return `(-${xs[0]})`;
          if (e.op === "not") return `(!${xs[0]})`;
          if (e.op === "float32") return `((double)(float)${xs[0]})`;
          if (e.op === "mod") return `lab_mod(${xs.join(", ")})`;
          return `${LIBM[e.op] ?? FDLIBM[e.op]}(${xs.join(", ")})`;
        }
        default: throw new Error(`${e.k} in C comes with NATIVE.md's later stages`);
      }
    }

    // Statements that end by returning e's value, or setting a variable to it.
    function block(e: SExpr, to: { set: string } | "return", d: string): string[] {
      const out: string[] = [];
      if (e.k === "let") {
        out.push(`${d}${local(e.i)} = ${ex(e.value, out, d)};`);
        return [...out, ...block(e.body, to, d)];
      }
      if (e.k === "if") {
        const c = ex(e.cond, out, d);
        return [...out, `${d}if (${c}) {`, ...block(e.then, to, d + "  "), `${d}} else {`, ...block(e.else, to, d + "  "), `${d}}`];
      }
      if (to === "return" && e.k === "call" && e.fn === i && e.tail) {
        // The loop's next round: every new value computed before any is set.
        const xs = e.args.map((a) => ex(a, out, d));
        const ts = xs.map((x, j) => (x === `p${j}` ? null : { t: temp(f.params[j]), x, j }));
        for (const t of ts) if (t) out.push(`${d}${t.t} = ${t.x};`);
        for (const t of ts) if (t) out.push(`${d}p${t.j} = ${t.t};`);
        return [...out, `${d}continue;`];
      }
      const x = ex(e, out, d);
      return [...out, to === "return" ? `${d}return ${x};` : `${d}${to.set} = ${x};`];
    }

    // One from the budget per call, and per round of the loop.
    const spend = (d: string) => (f.spends ? [`${d}lab_fuel -= 1;`, `${d}if (lab_fuel < 0) return ${zero(f.result)};`] : []);
    const body = loops ? ["  for (;;) {", ...spend("    "), ...block(f.body, "return", "    "), "  }"] : [...spend("  "), ...block(f.body, "return", "  ")];
    // Only the locals the body uses (the lowering's own for budgets aren't).
    const all = body.join("\n"), named = decls.filter((x) => new RegExp(`\\b${/(\w+);$/.exec(x)![1]}\\b`).test(all));
    return [`// ${f.name.replace(/\n/g, " ")}`, `${header(f, i)} {`, ...named, ...body, "}"].join("\n");
  }

  // What a function that ran out gives, which the budget around it replaces.
  function zero(t: LType): string {
    return t === "f64" || t === "i32" ? "0" : `((${ty(t)}){ ${(t as RType).fields.map((x) => zero(x.t)).join(", ")} })`;
  }

  function harness(): string {
    const cases = funcs.map((f, i) => {
      if (!f.params.every((t) => t === "f64" || t === "i32")) return "";
      // Read in order: C doesn't say in which order a call's arguments run.
      const args = f.params.map((t, j) => `${ty(t)} a${j} = ${t === "f64" ? "lab_in()" : "(int32_t)lab_bits()"};`);
      const outs = (t: LType, v: string): string[] => (isRecord(t) ? t.fields.flatMap((x, j) => outs(x.t, `${v}.f${j}`)) : [t === "f64" ? `lab_out(${v});` : `printf(" %d", (int)${v});`]);
      return `    case ${i}: { ${args.join(" ")} ${ty(f.result)} r = ${names.get(i)}(${f.params.map((_, j) => `a${j}`).join(", ")}); ${outs(f.result, "r").join(" ")} break; }`;
    }).filter(Boolean);
    return `#include <stdio.h>
#include <string.h>
static uint64_t lab_bits(void) { unsigned long long u = 0; if (scanf("%llx", &u) != 1) return 0; return u; }
static double lab_in(void) { uint64_t u = lab_bits(); double d; memcpy(&d, &u, 8); return d; }
static void lab_out(double d) { uint64_t u; memcpy(&u, &d, 8); printf(" %016llx", (unsigned long long)u); }
int main(void) {
  int i;
  while (scanf("%d", &i) == 1) {
    switch (i) {
${cases.join("\n")}
    }
    printf("\\n");
  }
  return 0;
}`;
  }
}

// A number as C reads it back exactly: JavaScript's shortest digits are
// enough for strtod too.
function num(v: number): string {
  if (Number.isNaN(v)) return "NAN";
  if (!Number.isFinite(v)) return v > 0 ? "INFINITY" : "(-INFINITY)";
  if (Object.is(v, -0)) return "(-0.0)";
  const s = String(v);
  const lit = /[.e]/.test(s) ? s : `${s}.0`;
  return v < 0 ? `(${lit})` : lit;
}

function calls(e: SExpr): Extract<SExpr, { k: "call" }>[] {
  switch (e.k) {
    case "call": return [e, ...e.args.flatMap(calls)];
    case "op": case "make": return e.args.flatMap(calls);
    case "get": return calls(e.rec);
    case "if": return [...calls(e.cond), ...calls(e.then), ...calls(e.else)];
    case "let": return [...calls(e.value), ...calls(e.body)];
    case "budget": return [...calls(e.body), ...calls(e.otherwise)];
    default: return [];
  }
}

function usesAny(e: SExpr, ops: Op[]): boolean {
  if (e.k === "op" && ops.includes(e.op)) return true;
  switch (e.k) {
    case "op": case "make": case "call": return e.args.some((a) => usesAny(a, ops));
    case "get": return usesAny(e.rec, ops);
    case "if": return [e.cond, e.then, e.else].some((a) => usesAny(a, ops));
    case "let": return usesAny(e.value, ops) || usesAny(e.body, ops);
    case "budget": return usesAny(e.body, ops) || usesAny(e.otherwise, ops);
    default: return false;
  }
}
