// Writes ../src/c-math.ts: ieee754.cc (V8's port of fdlibm, the code
// Node's Math runs) as plain C, for native programs (NATIVE.md), so a
// compiled program's sin, cos, tan, exp, log, pow and atan2 give the
// evaluator's bits on any C compiler. The C++ in it is small: namespaces,
// static_cast, V8's bit_cast and a few helpers. Run with
//   node math/to-c.ts
// Each function V8 defines becomes lab_fdlibm_<name>; the ones in its
// anonymous namespace become static.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const here = import.meta.dirname;
const src = readFileSync(join(here, "ieee754.cc"), "utf8");
const lines = src.split("\n");
const anonStart = lines.findIndex((l) => l === "namespace {"), anonEnd = lines.findIndex((l, i) => i > anonStart && l === "}  // namespace");
const names = new Set<string>();
const out = lines.map((l, i) => {
  if (/^#include/.test(l) || /^namespace \w*\s*\{$/.test(l) || /^}\s+\/\/ namespace/.test(l)) return "";
  const def = /^(?:static )?(?:inline )?(double|int32_t|int) (\w+)\(/.exec(l);
  if (def) names.add(def[2]);
  // Declarations and definitions in the anonymous namespace are this file's own.
  return i > anonStart && i < anonEnd && def && !l.startsWith("static") ? `static ${l}` : l;
});
let c = out.join("\n")
  .replace(/base::bit_cast<(\w+)>/g, "lab_as_$1")
  .replace(/static_cast<([\w ]+)>/g, "($1)")
  .replace(/base::Divide/g, "lab_divide")
  .replace(/NegateWithWraparound<int32_t>/g, "lab_negate")
  .replace(/std::numeric_limits<double>::(\w+)\(\)/g, (_, k: string) => (k === "infinity" ? "INFINITY" : "NAN"))
  .replace(/V8_WARN_UNUSED_RESULT/g, "")
  .replace(/V8_INLINE/g, "static inline")
  .replace(/const_cast<([\w *]+)>/g, "($1)")
  .replace(/SubWithWraparound/g, "lab_sub")
  .replace(/while \(false\)/g, "while (0)")
  // C++14's digit separators (0x0000'0000'FFFF'FFFF).
  .replace(/\b0x[0-9A-Fa-f']+/g, (n) => n.replace(/'/g, ""))
  .replace(/\n{3,}/g, "\n\n");
// Renamed in the code, not in the comments.
c = c.split(/(\/\*[\s\S]*?\*\/|\/\/.*)/).map((part, i) => (i % 2 ? part : [...names].reduce((x, n) => x.replace(new RegExp(`\\b${n}\\(`, "g"), `lab_fdlibm_${n}(`), part))).join("");
// What the other functions call before it is defined.
const declared = [...names].filter((n) => !new RegExp(`^static .*\\b(lab_fdlibm_)?${n}\\(`, "m").test(c)).map((n) => `double lab_fdlibm_${n}(double${["atan2", "pow"].includes(n) ? ", double" : ""});`);
if (/::|<\w+>/.test(c.replace(/\/\*[\s\S]*?\*\/|\/\/.*/g, ""))) throw new Error("C++ left in the C");

const prelude = `#include <stdint.h>
#include <string.h>
#include <math.h>
// What ieee754.cc took from V8: bit_cast as memcpy, and two helpers.
static inline uint64_t lab_as_uint64_t(double d) { uint64_t u; memcpy(&u, &d, 8); return u; }
static inline double lab_as_double(uint64_t u) { double d; memcpy(&d, &u, 8); return d; }
static inline double lab_divide(double a, double b) { return a / b; }
static inline int32_t lab_negate(int32_t a) { return (int32_t)(0u - (uint32_t)a); }
static inline int32_t lab_sub(int32_t a, int32_t b) { return (int32_t)((uint32_t)a - (uint32_t)b); }
#define V8_CC_MSVC 0
${declared.join("\n")}
`;
writeFileSync(join(here, "../src/c-math.ts"), `// Generated by math/to-c.ts from math/ieee754.cc, V8's port of fdlibm
// (Copyright (C) 1993 by Sun Microsystems, Inc.: "Permission to use, copy,
// modify, and distribute this software is freely granted, provided that
// this notice is preserved"; modified by the V8 project authors, BSD
// licence), as C. Don't edit: change to-c.ts and run it.
//
// sin, cos, tan, exp, log, pow and atan2 as V8 (so Node's Math) computes
// them, for native programs (c.ts): the same bits on every input.

export const FDLIBM_C = ${JSON.stringify(prelude + c)};
`);
console.log(`${names.size} functions`);
